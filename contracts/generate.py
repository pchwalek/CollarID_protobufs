#!/usr/bin/env python3
"""Generate the per-language contract constants from collarid_contracts.json.

    python3 generate.py          # write contracts/generated/*
    python3 generate.py --check  # exit 1 if any generated file is stale

Every file carries CONTRACTS_SHA256, the hash of the spec it came from
(canonical JSON, sorted keys, no 'about'). A repo's own test compares that
hash with the spec it vendors, so a hand edit or a half-done sync fails there.
Standard library only.
"""

import argparse
import hashlib
import json
import os
import pprint
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC_PATH = os.path.join(HERE, "collarid_contracts.json")
OUT = os.path.join(HERE, "generated")
BANNER = ("GENERATED by CollarID_protobufs/contracts/generate.py from collarid_contracts.json. "
          "Do not edit: change the spec, regenerate, sync (contracts/README.md).")


def load(path=SPEC_PATH):
    with open(path) as fh:
        return json.load(fh)


def body(spec):
    """The spec without its prose: what the hash and the generated files cover."""
    return {k: v for k, v in spec.items() if k != "about"}


def sha256(spec):
    canon = json.dumps(body(spec), sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canon.encode()).hexdigest()


def _ident(s):
    return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()


def c_header(spec):
    h, L = sha256(spec), []
    L += [f"/* {BANNER} */", "#ifndef COLLARID_CONTRACTS_H", "#define COLLARID_CONTRACTS_H", "",
          f"#define CID_CONTRACTS_VERSION {spec['version']}u",
          f'#define CID_CONTRACTS_SHA256 "{h}"', "", "/* Bluetooth service and characteristics */"]
    for k, v in spec["gatt"].items():
        L.append(f'#define CID_GATT_{_ident(k)} "{v}"')
    c = spec["caps"]
    L += ["", "/* The radio's capability characteristic */",
          f'#define CID_CAPS_MAGIC "{c["magic"]}"']
    for k in ("format_family", "format_build", "family_offset", "build_offset", "length"):
        L.append(f"#define CID_CAPS_{_ident(k)} {c[k]}u")
    for k, v in c["bits"].items():
        L.append(f"#define CID_CAPS_BIT_{_ident(k)} 0x{v:02X}u")
    for k, v in c["families"].items():
        L.append(f"#define CID_CAPS_FAMILY_{_ident(k)} 0x{v:02X}u")
    d = spec["dfu"]
    L += ["", "/* Firmware update over Bluetooth */"]
    for k, v in d["special_mode"].items():
        L.append(f"#define CID_DFU_MODE_{_ident(k)} {v}u")
    for k in ("mtu_publish_tag", "frame_start", "frame_data", "frame_end"):
        L.append(f"#define CID_DFU_{_ident(k)} 0x{d[k]:02X}u")
    for k in ("frame_overhead", "batch_frames", "u5_header_len", "u5_header_version",
              "u5_payload_cap", "radio_payload_cap", "payload_fallback"):
        L.append(f"#define CID_DFU_{_ident(k)} {d[k]}u")
    L.append(f'#define CID_DFU_U5_MAGIC "{d["u5_magic"]}"')
    for k, v in d["targets"].items():
        L.append(f"#define CID_DFU_TARGET_{_ident(k)} 0x{v:02X}u")
    L += ["", "/* Build stamps in an image */"]
    for k, v in spec["version_report"]["image_tags"].items():
        L.append(f'#define CID_IMAGE_TAG_{_ident(k)} "{v}"')
    L += ["", "/* ErrorFlags.flag */"]
    for b in spec["error_flags"]["bits"]:
        L.append(f"#define CID_ERROR_FLAG_{_ident(b['key'])} (1u << {b['bit']})   /* {b['what']} */")
    L.append(f"#define CID_ERROR_FLAGS_FIRST_FREE {spec['error_flags']['first_free']}u")
    cfg = spec.get("config_csv")
    if isinstance(cfg, dict):
        L += ["", "/* CONFIG.CSV: X-macro lists, X(\"key\") per key, in file order */",
              f'#define CID_CONFIG_CSV_SCHEDULE_HEADER "{cfg["schedule_header"]}"',
              f"#define CID_CONFIG_CSV_SCHEDULE_COLUMNS {cfg['schedule_columns']}u"]
        for section, keys in cfg["keys"].items():
            L.append(f"#define CID_CONFIG_CSV_{_ident(section)}_KEYS(X) \\")
            L += [f'    X("{k}") \\' for k in keys]
            L.append("")
            L.append(f"#define CID_CONFIG_CSV_{_ident(section)}_COUNT {len(keys)}u")
        for section in ("conditional", "firmware_only"):
            L.append(f"#define CID_CONFIG_CSV_{_ident(section)}_KEYS(X) \\")
            L += [f'    X("{k}") \\' for k in cfg[section]]
            L.append("")
    L += ["", "#endif /* COLLARID_CONTRACTS_H */", ""]
    return "\n".join(L)


def _js_literal(spec):
    return json.dumps(body(spec), indent=2, ensure_ascii=False)


def ts_module(spec):
    return (f"// {BANNER}\n"
            "/* eslint-disable */\n"
            f"export const CONTRACTS_SHA256 = '{sha256(spec)}';\n"
            f"export const CONTRACTS = {_js_literal(spec)} as const;\n"
            "export default CONTRACTS;\n")


def js_module(spec):
    """Browser global CollarIDContracts, or module.exports under node."""
    return (f"// {BANNER}\n"
            "(function (root, make) {\n"
            "  'use strict';\n"
            "  const c = make();\n"
            "  if (typeof module === 'object' && module.exports) module.exports = c;\n"
            "  else root.CollarIDContracts = c;\n"
            "})(typeof self !== 'undefined' ? self : this, function () {\n"
            "  'use strict';\n"
            f"  const C = {_js_literal(spec)};\n"
            f"  C.CONTRACTS_SHA256 = '{sha256(spec)}';\n"
            "  return Object.freeze(C);\n"
            "});\n")


def py_module(spec):
    return (f'"""{BANNER}"""\n\n'
            f"CONTRACTS_SHA256 = {sha256(spec)!r}\n\n"
            f"CONTRACTS = {pprint.pformat(body(spec), width=100, sort_dicts=False)}\n")


FILES = {
    "collarid_contracts.h": c_header,
    "collaridContracts.ts": ts_module,
    "collarid-contracts.js": js_module,
    "collarid_contracts.py": py_module,
}


def render(spec=None):
    spec = spec or load()
    return {name: fn(spec) for name, fn in FILES.items()}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    out = render()
    stale = []
    os.makedirs(OUT, exist_ok=True)
    for name, text in out.items():
        path = os.path.join(OUT, name)
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(name)
            if not a.check:
                with open(path, "w") as fh:
                    fh.write(text)
    if a.check:
        print("stale: " + ", ".join(stale) if stale else "generated files are current")
        return 1 if stale else 0
    print("wrote " + (", ".join(stale) if stale else "nothing (all current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
